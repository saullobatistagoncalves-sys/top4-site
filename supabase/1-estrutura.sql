-- ---------- Opcional: cancelar reservas esquecidas ----------
-- Devolve ao estoque os pedidos que ficaram "reservado" por mais de 48 horas.
-- Para rodar sozinho a cada hora, ative a extensão pg_cron (Database → Extensions)
-- e rode depois:  select cron.schedule('expirar-reservas', '0 * * * *', 'select public.expirar_reservas()');

create or replace function public.expirar_reservas(p_horas int default 48)
returns int
language plpgsql security definer
set search_path = public
as $$
declare
  v_ped public.pedidos%rowtype;
  it    jsonb;
  n     int := 0;
begin
  for v_ped in select * from public.pedidos
                where status = 'reservado' and criado_em < now() - make_interval(hours => p_horas)
                for update skip locked loop
    for it in select value from jsonb_array_elements(v_ped.itens) loop
      update public.estoque set quantidade = quantidade + (it->>'qtd')::int
       where produto_id = (it->>'produto_id')::bigint and tamanho = it->>'tamanho';
    end loop;
    update public.pedidos set status = 'cancelado', atualizado_em = now() where id = v_ped.id;
    n := n + 1;
  end loop;
  return n;
end;
$$;
revoke execute on function public.expirar_reservas(int) from public, anon, authenticated;
