-- ---------- Tabelas ----------

create table if not exists public.produtos (
  id           bigint generated by default as identity primary key,
  nome         text        not null check (char_length(nome) between 2 and 120),
  descricao    text        not null default '',
  genero       text        not null default 'u' check (genero in ('m','f','u')),   -- m masculino, f feminino, u unissex
  categorias   text[]      not null default '{}',                               -- calcados, esportes, acessorios
  tipo         text        not null default 'tshirt',                           -- desenho usado quando não há foto
  cor_nome     text        not null default '',
  cor1         text        not null default '#1A1A1B',
  cor2         text        not null default '#C29A5B',
  preco        numeric(10,2) not null check (preco >= 0),
  preco_de     numeric(10,2) check (preco_de is null or preco_de >= 0),         -- preço "de" (riscado)
  novo         boolean     not null default false,
  tags         text        not null default '',                                 -- palavras para a busca
  foto_url     text,
  ordem        int         not null default 0,
  ativo        boolean     not null default true,
  criado_em    timestamptz not null default now()
);

create table if not exists public.estoque (
  produto_id   bigint  not null references public.produtos(id) on delete cascade,
  tamanho      text    not null check (char_length(tamanho) between 1 and 12),
  quantidade   int     not null default 0 check (quantidade >= 0),
  ordem        int     not null default 0,
  primary key (produto_id, tamanho)
);

create table if not exists public.pedidos (
  id            bigint generated always as identity primary key,
  codigo        text        not null unique,
  itens         jsonb       not null,
  total         numeric(10,2) not null,
  cliente_nome  text,
  status        text        not null default 'reservado' check (status in ('reservado','confirmado','cancelado')),
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists pedidos_criado_em_idx on public.pedidos (criado_em desc);

-- Quem pode entrar no painel. Só quem estiver nesta tabela é lojista.
create table if not exists public.admins (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  criado_em timestamptz not null default now()
);

-- ---------- Quem é lojista ----------

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------- Regras de acesso (RLS) ----------

alter table public.produtos enable row level security;
alter table public.estoque  enable row level security;
alter table public.pedidos  enable row level security;
alter table public.admins   enable row level security;

drop policy if exists "produtos: todos veem os ativos"   on public.produtos;
drop policy if exists "produtos: lojista cria"           on public.produtos;
drop policy if exists "produtos: lojista edita"          on public.produtos;
drop policy if exists "produtos: lojista apaga"          on public.produtos;
create policy "produtos: todos veem os ativos" on public.produtos for select using (ativo or public.is_admin());
create policy "produtos: lojista cria"         on public.produtos for insert to authenticated with check (public.is_admin());
create policy "produtos: lojista edita"        on public.produtos for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "produtos: lojista apaga"        on public.produtos for delete to authenticated using (public.is_admin());

drop policy if exists "estoque: todos veem"     on public.estoque;
drop policy if exists "estoque: lojista cria"   on public.estoque;
drop policy if exists "estoque: lojista edita"  on public.estoque;
drop policy if exists "estoque: lojista apaga"  on public.estoque;
create policy "estoque: todos veem"    on public.estoque for select using (true);
create policy "estoque: lojista cria"  on public.estoque for insert to authenticated with check (public.is_admin());
create policy "estoque: lojista edita" on public.estoque for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "estoque: lojista apaga" on public.estoque for delete to authenticated using (public.is_admin());

-- Pedidos: o cliente nunca lê nem grava direto; ele só usa a função reservar_pedido.
drop policy if exists "pedidos: lojista vê" on public.pedidos;
create policy "pedidos: lojista vê" on public.pedidos for select to authenticated using (public.is_admin());

drop policy if exists "admins: cada um vê a si" on public.admins;
create policy "admins: cada um vê a si" on public.admins for select to authenticated using (user_id = auth.uid());

-- Permissões de tabela (o RLS acima continua decidindo linha a linha)
grant usage on schema public to anon, authenticated;
grant select on public.produtos, public.estoque to anon, authenticated;
grant insert, update, delete on public.produtos, public.estoque to authenticated;
grant select on public.pedidos, public.admins to authenticated;
revoke insert, update, delete on public.pedidos from anon, authenticated;

-- ---------- Reserva do pedido (chamada pela loja) ----------
-- Baixa o estoque de todos os itens de uma vez. Se faltar qualquer um,
-- nada é baixado. O preço vem do banco, nunca do navegador do cliente.

create or replace function public.reservar_pedido(p_itens jsonb, p_cliente text default null)
returns json
language plpgsql security definer
set search_path = public
as $$
declare
  it        jsonb;
  v_prod    public.produtos%rowtype;
  v_qtd     int;
  v_tam     text;
  v_rows    int;
  v_total   numeric(10,2) := 0;
  v_itens   jsonb := '[]'::jsonb;
  v_codigo  text;
begin
  if p_itens is null or jsonb_typeof(p_itens) <> 'array'
     or jsonb_array_length(p_itens) = 0 or jsonb_array_length(p_itens) > 30 then
    raise exception 'PEDIDO_INVALIDO';
  end if;

  for it in select value from jsonb_array_elements(p_itens) loop
    begin
      v_qtd := (it->>'qtd')::int;
    exception when others then
      raise exception 'PEDIDO_INVALIDO';
    end;
    v_tam := it->>'tamanho';
    if v_qtd is null or v_qtd < 1 or v_qtd > 20 or v_tam is null then
      raise exception 'PEDIDO_INVALIDO';
    end if;

    select * into v_prod from public.produtos
      where id = (it->>'produto_id')::bigint and ativo;
    if not found then
      raise exception 'PRODUTO_INDISPONIVEL';
    end if;

    update public.estoque
       set quantidade = quantidade - v_qtd
     where produto_id = v_prod.id and tamanho = v_tam and quantidade >= v_qtd;
    get diagnostics v_rows = row_count;
    if v_rows = 0 then
      raise exception 'SEM_ESTOQUE|%|%', v_prod.nome, v_tam;
    end if;

    v_total := v_total + v_prod.preco * v_qtd;
    v_itens := v_itens || jsonb_build_object(
      'produto_id', v_prod.id, 'nome', v_prod.nome, 'tamanho', v_tam,
      'qtd', v_qtd, 'preco', v_prod.preco);
  end loop;

  loop
    v_codigo := 'T4-' || to_char(now() at time zone 'America/Sao_Paulo', 'DDMM') || '-'
                || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 4));
    exit when not exists (select 1 from public.pedidos where codigo = v_codigo);
  end loop;

  insert into public.pedidos (codigo, itens, total, cliente_nome)
  values (v_codigo, v_itens, v_total, nullif(left(trim(coalesce(p_cliente,'')), 80), ''));

  return json_build_object('codigo', v_codigo, 'total', v_total, 'itens', v_itens);
end;
$$;

-- ---------- Ações do lojista ----------

create or replace function public.confirmar_pedido(p_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'SEM_PERMISSAO'; end if;
  update public.pedidos set status = 'confirmado', atualizado_em = now()
   where id = p_id and status = 'reservado';
  if not found then raise exception 'PEDIDO_NAO_RESERVADO'; end if;
end;
$$;

-- Cancela e devolve as peças ao estoque (reservado ou confirmado).
create or replace function public.cancelar_pedido(p_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_ped public.pedidos%rowtype;
  it    jsonb;
begin
  if not public.is_admin() then raise exception 'SEM_PERMISSAO'; end if;
  select * into v_ped from public.pedidos where id = p_id for update;
  if not found or v_ped.status = 'cancelado' then raise exception 'PEDIDO_JA_CANCELADO'; end if;

  for it in select value from jsonb_array_elements(v_ped.itens) loop
    insert into public.estoque (produto_id, tamanho, quantidade)
    select (it->>'produto_id')::bigint, it->>'tamanho', (it->>'qtd')::int
     where exists (select 1 from public.produtos where id = (it->>'produto_id')::bigint)
    on conflict (produto_id, tamanho)
    do update set quantidade = public.estoque.quantidade + excluded.quantidade;
  end loop;

  update public.pedidos set status = 'cancelado', atualizado_em = now() where id = p_id;
end;
$$;

revoke execute on function public.reservar_pedido(jsonb, text) from public;
revoke execute on function public.confirmar_pedido(bigint)     from public;
revoke execute on function public.cancelar_pedido(bigint)      from public;
grant  execute on function public.reservar_pedido(jsonb, text) to anon, authenticated;
grant  execute on function public.confirmar_pedido(bigint)     to authenticated;
grant  execute on function public.cancelar_pedido(bigint)      to authenticated;
grant  execute on function public.is_admin()                   to anon, authenticated;

